import { createContext, useContext, useEffect, useState } from "react";
import type { AppLanguage, KeybindingAction, TerminalThemeName } from "./types";

export type UiLocale = Exclude<AppLanguage, "system">;

export function resolveAppLocale(language: AppLanguage): UiLocale {
  if (language !== "system") return language;
  const candidates = typeof navigator === "undefined" ? [] : navigator.languages?.length ? navigator.languages : [navigator.language];
  return candidates.some((candidate) => candidate?.toLowerCase().startsWith("zh")) ? "zh-CN" : "en-US";
}

export function useResolvedAppLocale(language: AppLanguage): UiLocale {
  const [systemLocale, setSystemLocale] = useState(() => resolveAppLocale("system"));
  useEffect(() => {
    if (language !== "system") return;
    const update = () => setSystemLocale(resolveAppLocale("system"));
    window.addEventListener("languagechange", update);
    return () => window.removeEventListener("languagechange", update);
  }, [language]);
  return language === "system" ? systemLocale : language;
}

